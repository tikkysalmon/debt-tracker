-- ============================================================
-- ระบบติดตามหนี้ — แก้ปัญหาข้อมูลเด้งกลับเมื่อมีคนบันทึกพร้อมกันหลายคน (2026-08-05)
-- วางทั้งหมดนี้ใน Supabase → SQL Editor → New query → Run (รันได้ทันที ไม่กระทบเว็บที่ใช้งานอยู่ —
-- ต้อง deploy โค้ด index.html เวอร์ชันใหม่ (ที่รู้จักตาราง app_state_sync นี้) ควบคู่ไปด้วยถึงจะเริ่ม
-- ใช้งานจริง ถ้ารันแค่ SQL นี้แต่ยังไม่ deploy โค้ด จะไม่มีผลอะไรเลย ไม่ error)
--
-- ปัญหาเดิม: ข้อมูลหลัก (~15-20MB) เก็บเป็นไฟล์ใน Supabase Storage (app-data/state.json) ไม่ใช่แถวใน
-- ตาราง Postgres เพราะเขียนขนาดนี้ผ่านตารางปกติจะติด statement_timeout ของ role ที่ใช้ แต่การอัปโหลด
-- ไฟล์ใน Storage ไม่มีกลไก "บันทึกทับได้ก็ต่อเมื่อไม่มีใครแก้ไปตั้งแต่ที่เราโหลดมา" (compare-and-swap)
-- ให้ใช้เลย โค้ดเดิมแก้ปัญหานี้ด้วยการเช็ค updated_at ซ้ำก่อนอัปโหลดจริง ถ้าเปลี่ยนไปแล้วก็ผสานข้อมูล
-- ใหม่แล้วลองใหม่ (สูงสุด 5 ครั้ง) ซึ่งช่วยได้เยอะตอนมีคนใช้พร้อมกัน 1-2 คน แต่ยังมีช่องว่างเล็กๆ
-- ระหว่าง "เช็คแล้วว่ายังไม่เปลี่ยน" กับ "อัปโหลดเสร็จจริง" ที่ปิดไม่สนิท — ยิ่งมีคนบันทึกพร้อมกันมาก
-- (3 คนขึ้นไป) โอกาสชนช่องว่างนี้ก็ยิ่งสูงขึ้นมาก จนข้อมูลบางส่วนถูกเขียนทับเงียบๆ ("เด้งกลับ")
--
-- ทางแก้: ตารางเล็กๆ นี้เก็บแค่ "ใครกำลังถือคิวบันทึกอยู่" (ไม่ใช่ข้อมูลลูกหนี้เลย) — ก่อนบันทึกทุกครั้ง
-- ฝั่งเว็บจะขอ "ล็อก" แถวนี้ก่อน (เป็นคำสั่ง UPDATE ... WHERE เดียว ซึ่ง Postgres รับประกันว่าถ้ามีคน
-- ยิงพร้อมกันหลายคน จะมีคนเดียวเท่านั้นที่ชนะ) แล้วค่อยโหลด-ผสาน-อัปโหลดข้อมูลจริงระหว่างที่ถือล็อกอยู่
-- คนอื่นที่มาขอบันทึกพร้อมกันจะต้องรอคิวจนกว่าคนแรกจะปล่อยล็อก (ปกติไม่กี่วินาที) แทนที่จะแย่งกันเขียน
-- ทับกันเงียบๆ แบบเดิม — ปิดช่องโหว่นี้ได้จริง ไม่ใช่แค่ทำให้แคบลงเหมือนวิธีเดิม
-- มีระบบกันล็อกค้าง (25 วินาที) ไว้ด้วย เผื่อพนักงานคนใดปิดแท็บ/เน็ตหลุดระหว่างถือล็อกอยู่พอดี
-- ============================================================

create table if not exists app_state_sync (
  id smallint primary key default 1,
  version bigint not null default 0,   -- ไม่ได้ใช้ตัดสินใจอะไรในโค้ดตอนนี้ เผื่อ debug/ต่อยอดในอนาคต
  locked_by text,                      -- myClientId ของฝั่งเว็บที่ถือล็อกอยู่ (null = ว่าง)
  locked_at timestamptz,               -- เวลาที่ขอ/ต่อล็อกล่าสุด ใช้เช็คว่าล็อกค้างหรือยัง
  constraint app_state_sync_singleton check (id = 1)
);

insert into app_state_sync (id, version) values (1, 0)
  on conflict (id) do nothing;

alter table app_state_sync enable row level security;

-- แถวนี้ไม่มีข้อมูลลูกหนี้/ข้อมูลอ่อนไหวใดๆ เลย (แค่ตัวนับ + ว่าใครถือคิวบันทึกอยู่) พนักงานที่
-- ล็อกอินแล้วทุกคนอ่าน/แก้ได้เหมือนกันหมด ไม่ต้องแยกสิทธิ์ละเอียดแบบ staff_users
drop policy if exists "app_state_sync authenticated read" on app_state_sync;
create policy "app_state_sync authenticated read" on app_state_sync
  for select to authenticated using (true);

drop policy if exists "app_state_sync authenticated update" on app_state_sync;
create policy "app_state_sync authenticated update" on app_state_sync
  for update to authenticated using (true) with check (true);

-- เท่านี้เสร็จ — deploy index.html เวอร์ชันใหม่แล้วระบบจะเริ่มใช้ล็อกนี้ทันทีตั้งแต่การบันทึกครั้งถัดไป
